// Helper to generate past dates
const getDateDaysAgo = (days: number, timeStr: string = '15:30:00'): string => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  const datePart = d.toISOString().split('T')[0];
  return `${datePart}T${timeStr}Z`;
};

